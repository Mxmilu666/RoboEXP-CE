    public static string Get(string key, UiLanguage language) => TryGet(key, language) ?? key;

    public static string? TryGet(string key, UiLanguage language)
    {
        if (!Table.TryGetValue(key, out var t)) return null;
        return language switch { UiLanguage.CHS => t.Chs, UiLanguage.CHT => t.Cht, _ => t.En };
    }
