#!/usr/bin/env python3
"""Generate Avalonia path geometry from pinned Lucide SVGs (ISC license).
Usage: python3 tools/generate-flat-icons.py
Downloads the pinned npm archive; only selected SVG geometry is embedded in the app.
"""
import hashlib
import io
import json
from pathlib import Path
import tarfile
import urllib.request
import xml.etree.ElementTree as ET

VERSION = '1.64.0'
SHA1 = '4e673aa08d67c2b5f7943dd95577af2e2c75c1a0'
GLYPHS = '''file-plus folder-open book-open save save-all printer log-out undo-2 redo-2 scissors copy clipboard trash-2
square-dashed-mouse-pointer layout-grid code-xml sliders-horizontal variable file-code terminal cpu hammer download info
hand mouse-pointer-2 cable type align-start-vertical align-end-vertical align-start-horizontal align-end-horizontal
workflow rows-3 grid-2x2 folder-tree circle-check triangle-alert circle-x rotate-cw shapes arrow-left-right usb power'''.split()


def geometry(node):
    a = node.attrib
    kind = node.tag.split('}')[-1]
    if kind == 'path': return a['d']
    if kind == 'line': return f'M {a["x1"]},{a["y1"]} L {a["x2"]},{a["y2"]}'
    if kind in ('polyline', 'polygon'): return 'M ' + a['points'] + (' Z' if kind == 'polygon' else '')
    if kind == 'circle':
        x, y, r = (float(a[k]) for k in ('cx', 'cy', 'r'))
        return f'M {x-r},{y} A {r},{r} 0 1 0 {x+r},{y} A {r},{r} 0 1 0 {x-r},{y}'
    if kind == 'ellipse':
        x,y,rx,ry=(float(a[k]) for k in ('cx','cy','rx','ry'))
        return f'M {x-rx},{y} A {rx},{ry} 0 1 0 {x+rx},{y} A {rx},{ry} 0 1 0 {x-rx},{y}'
    if kind == 'rect':
        x,y,w,h=(float(a.get(k,0)) for k in ('x','y','width','height'))
        r=min(float(a.get('rx',0)),w/2,h/2)
        return (f'M {x+r},{y} H {x+w-r} Q {x+w},{y} {x+w},{y+r} V {y+h-r} '
                f'Q {x+w},{y+h} {x+w-r},{y+h} H {x+r} Q {x},{y+h} {x},{y+h-r} '
                f'V {y+r} Q {x},{y} {x+r},{y} Z')
    raise ValueError(f'Unsupported SVG element: {kind}')

archive = urllib.request.urlopen(f'https://registry.npmjs.org/lucide-static/-/lucide-static-{VERSION}.tgz').read()
if hashlib.sha1(archive).hexdigest() != SHA1: raise ValueError('Lucide archive integrity check failed')
with tarfile.open(fileobj=io.BytesIO(archive),mode='r:gz') as t:
    entries=[]
    for name in sorted(set(GLYPHS)):
        svg=ET.fromstring(t.extractfile(f'package/icons/{name}.svg').read())
        paths=[geometry(n) for n in svg]
        entries.append('        ['+json.dumps(name)+'] = ['+', '.join(json.dumps(p) for p in paths)+'],')
    license_text=t.extractfile('package/LICENSE').read().decode()
root=Path(__file__).resolve().parents[1]
out=root/'src/RoboExp.App/Icons/LucidePaths.g.cs'
out.parent.mkdir(parents=True,exist_ok=True)
out.write_text('// Generated by tools/generate-flat-icons.py; Lucide '+VERSION+' (ISC). Do not edit.\n'
               'namespace RoboExp.App.Icons;\n\ninternal static class LucidePaths\n{\n'
               '    internal static readonly IReadOnlyDictionary<string, string[]> Data = new Dictionary<string, string[]>\n    {\n'
               +'\n'.join(entries)+'\n    };\n}\n')
(root/'THIRD-PARTY-NOTICES').write_text('Lucide '+VERSION+' — https://lucide.dev\nUsed for flat action icons and download-step illustrations.\n\n'+license_text)
print(f'Generated {len(entries)} vector glyphs: {out}')
